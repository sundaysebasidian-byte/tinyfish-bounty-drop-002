CREATE TABLE receipts(id TEXT PRIMARY KEY, data TEXT NOT NULL, created_at TEXT NOT NULL);
CREATE TABLE watches(id TEXT PRIMARY KEY, receipt_id TEXT NOT NULL UNIQUE, monitor_id TEXT UNIQUE, token TEXT NOT NULL, expires_at TEXT NOT NULL, state TEXT NOT NULL, last_error TEXT);
CREATE TABLE events(id TEXT PRIMARY KEY,watch_id TEXT NOT NULL,data TEXT NOT NULL,created_at TEXT NOT NULL);
CREATE TABLE costs(id TEXT PRIMARY KEY,primitive TEXT NOT NULL,usd REAL NOT NULL,day TEXT NOT NULL,created_at TEXT NOT NULL);
CREATE TABLE cache(key TEXT PRIMARY KEY,data TEXT NOT NULL,expires_at TEXT NOT NULL);
CREATE TABLE limits(key TEXT PRIMARY KEY,n INTEGER NOT NULL);
